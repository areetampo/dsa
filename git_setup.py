"""
One-time setup: turn this folder into a PUBLIC GitHub repo and schedule
git_sync.py to keep it up to date.

Steps (it tells you what it is doing and asks before publishing anything):
  1. checks git and the GitHub CLI (gh) are installed
  2. logs you in to GitHub (browser) and lets git push without a password prompt
  3. git init, and adds sensible ignore rules to .gitignore (.env, backups, logs...)
  4. sets the commit name/email for THIS repo to your GitHub no-reply address,
     so your real email is not published in the commit history
  5. shows what would be uploaded, then asks you to type PUBLIC to continue
  6. makes the first commit, creates the repo on GitHub and pushes
  7. registers a Windows scheduled task that runs git_sync.py every 30 minutes

Usage:
  py git_setup.py                   # full setup
  py git_setup.py --name dsa        # repo name on GitHub (default: dsa)
  py git_setup.py --interval 15     # minutes between syncs (default: 30)
  py git_setup.py --no-schedule     # skip the scheduled task
  py git_setup.py --unschedule      # remove the scheduled task and exit
"""

import argparse
import base64
import os
import shutil
import subprocess
import sys
from pathlib import Path

import git_sync

REPO = Path(__file__).resolve().parent
TASK_NAME = "DSA Git Sync"

GITIGNORE_LINES = [
    "# --- secrets (NEVER commit) ---",
    ".env",
    ".env.*",
    "!.env.example",
    "lc_submissions_import.py",
    "# --- temporary / generated by the restore + sync scripts ---",
    "urls.txt",
    "log.txt",
    "restore_*.log",
    "lc_rename_log.txt",
    "git_sync.log",
    ".git_sync.lock",
    "_placeholder_backup/",
    "_lc_backup/",
    "*.bak",
    "# --- build output ---",
    "outputs/",
    "dbg/",
    "*.exe",
    "*.o",
    "*.obj",
    "*.out",
    "*.pdb",
    "*.ilk",
    "# --- python / editor ---",
    "__pycache__/",
    "*.pyc",
    ".vscode/",
]

GITATTRIBUTES = "* text=auto eol=lf\n"


def say(msg=""):
    try:
        print(msg)
    except UnicodeEncodeError:
        print(msg.encode("ascii", "replace").decode("ascii"))


def die(msg):
    say(f"\nSTOP: {msg}")
    sys.exit(1)


def step(n, title):
    say(f"\n[{n}] {title}")


def run(cmd, capture=True):
    return subprocess.run(
        cmd,
        cwd=REPO,
        capture_output=capture,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def ensure_gitignore(repo):
    """Append missing rules to .gitignore (never removes or rewrites yours)."""
    path = repo / ".gitignore"
    existing = (
        path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    )
    have = {l.strip() for l in existing.splitlines()}
    # keep a comment header only if at least one rule under it is new
    out, pending_header = [], None
    for line in GITIGNORE_LINES:
        if line.startswith("#"):
            pending_header = line
            continue
        if line not in have:
            if pending_header:
                out.append(pending_header)
                pending_header = None
            out.append(line)
    if not out:
        return []
    text = existing
    if text and not text.endswith("\n"):
        text += "\n"
    if text:
        text += "\n"
    text += "\n".join(out) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")
    return [l for l in out if not l.startswith("#")]


def powershell_register(py_exe, script, workdir, minutes):
    q = lambda s: str(s).replace("'", "''")
    return f"""
$ErrorActionPreference = 'Stop'
$action = New-ScheduledTaskAction -Execute '{q(py_exe)}' -Argument '"{q(script)}"' -WorkingDirectory '{q(workdir)}'
$logon = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$repeat = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) -RepetitionInterval (New-TimeSpan -Minutes {int(minutes)}) -RepetitionDuration (New-TimeSpan -Days 3650)
$settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 10)
Register-ScheduledTask -TaskName '{q(TASK_NAME)}' -Action $action -Trigger @($logon, $repeat) -Settings $settings -Description 'Commit and push new solutions in the dsa folder to GitHub' -Force | Out-Null
Write-Host 'Scheduled task registered.'
"""


def run_powershell(script):
    encoded = base64.b64encode(script.encode("utf-16-le")).decode("ascii")
    return subprocess.run(
        [
            "powershell",
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-EncodedCommand",
            encoded,
        ],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )


def schedule(minutes):
    exe = Path(sys.executable)
    pyw = exe.with_name("pythonw.exe")
    py_exe = pyw if pyw.exists() else exe  # pythonw = no console window
    script = REPO / "git_sync.py"
    ps = powershell_register(py_exe, script, REPO, minutes)

    if os.name != "nt":
        say("Not on Windows, so the scheduled task was not created. It would run:")
        say(ps)
        return
    r = run_powershell(ps)
    if r.returncode != 0:
        say("Could not create the scheduled task:")
        say((r.stderr or r.stdout).strip())
        say(
            "The repo itself is fine. You can run `py git_sync.py` by hand, "
            "or re-run `py git_setup.py` to retry the scheduling."
        )
        return
    say(
        f"Scheduled task '{TASK_NAME}' created: runs {script.name} every "
        f"{minutes} minutes and at logon, even after a missed run."
    )


def unschedule():
    if os.name != "nt":
        say("Not on Windows; nothing to remove.")
        return
    r = run_powershell(
        f"Unregister-ScheduledTask -TaskName '{TASK_NAME}' -Confirm:$false; "
        "Write-Host 'Removed.'"
    )
    say((r.stdout or r.stderr).strip())


def main():
    ap = argparse.ArgumentParser(
        description="Set up the GitHub repo and sync schedule."
    )
    ap.add_argument("--name", default="dsa", help="repository name (default: dsa)")
    ap.add_argument("--interval", type=int, default=30, help="minutes between syncs")
    ap.add_argument("--no-schedule", action="store_true")
    ap.add_argument("--unschedule", action="store_true")
    args = ap.parse_args()

    if args.unschedule:
        unschedule()
        return
    if args.interval < 5:
        die("Pick an interval of 5 minutes or more.")

    # 1. tools -------------------------------------------------------------
    step(1, "Checking tools")
    if not shutil.which("git"):
        die(
            "Git is not installed. Run:  winget install --id Git.Git -e\n"
            "Then close and reopen the terminal and run this again."
        )
    if not shutil.which("gh"):
        die(
            "The GitHub CLI is not installed. Run:  winget install --id GitHub.cli -e\n"
            "Then close and reopen the terminal and run this again."
        )
    say("git and gh found.")

    # 2. login -------------------------------------------------------------
    step(2, "GitHub login")
    if run(["gh", "auth", "status"]).returncode != 0:
        say("Not logged in. A browser window will open to log in.")
        run(
            ["gh", "auth", "login", "-h", "github.com", "-p", "https", "-w"],
            capture=False,
        )
        if run(["gh", "auth", "status"]).returncode != 0:
            die("Login did not complete. Run `gh auth login` and try again.")
    run(["gh", "auth", "setup-git", "--hostname", "github.com"])  # push without prompts
    say("Logged in; git will use your GitHub login when pushing.")

    # 3. init + ignore -----------------------------------------------------
    step(3, "Preparing the folder")
    if not (REPO / ".git").exists():
        r = run(["git", "init", "-b", "main"])
        if r.returncode != 0:  # older git without -b
            run(["git", "init"])
            run(["git", "symbolic-ref", "HEAD", "refs/heads/main"])
        say("Created a new git repo.")
    else:
        say("Already a git repo.")
    added = ensure_gitignore(REPO)
    say(
        f"Added {len(added)} rule(s) to .gitignore."
        if added
        else ".gitignore already covers everything."
    )
    attrs = REPO / ".gitattributes"
    if not attrs.exists():
        attrs.write_text(GITATTRIBUTES, encoding="utf-8", newline="\n")
        say("Created .gitattributes (consistent line endings).")

    # 4. identity ----------------------------------------------------------
    step(4, "Commit identity (privacy)")
    login = run(["gh", "api", "user", "--jq", ".login"]).stdout.strip()
    uid = run(["gh", "api", "user", "--jq", ".id"]).stdout.strip()
    if not login or not uid:
        die("Could not read your GitHub username. Check `gh auth status`.")
    email = f"{uid}+{login}@users.noreply.github.com"
    run(["git", "config", "user.name", login])
    run(["git", "config", "user.email", email])
    say(f"Commits will use {login} <{email}>")
    say(
        "Tip: on github.com > Settings > Emails, tick 'Keep my email addresses private' "
        "and 'Block command line pushes that expose my email'."
    )

    # 5. preview + confirm -------------------------------------------------
    step(5, "What would be uploaded")
    res = git_sync.run(REPO, dry_run=True, settle=0)
    if res["errors"]:
        die("Could not read the folder state: " + "; ".join(res["errors"]))
    n = len(res["candidates"])
    if res["blocked"]:
        say("\nThese files look like they contain secrets and will NOT be uploaded:")
        for p, why in res["blocked"].items():
            say(f"  {p}  ({why})")
        say("Remove the secret (or delete the file) and they will be picked up later.")
    if run(["git", "remote", "get-url", "origin"]).returncode == 0:
        say(
            f"\nThe repo already exists on GitHub. {n} new/changed file(s) will be committed and pushed."
        )
    else:
        say(f"\nThis will create a PUBLIC repo '{login}/{args.name}' with {n} files.")
    say("Everything in it will be visible to anyone on the internet.")
    if input("Type PUBLIC to continue (anything else cancels): ").strip() != "PUBLIC":
        say("Cancelled. Nothing was committed or uploaded.")
        return

    # 6. first commit + repo ----------------------------------------------
    step(6, "First commit and GitHub repo")
    git_sync.run(REPO, settle=0, push=False)
    if run(["git", "rev-parse", "--verify", "-q", "HEAD"]).returncode != 0:
        die("Nothing was committed, so there is nothing to upload.")

    remote = run(["git", "remote", "get-url", "origin"])
    if remote.returncode == 0:
        say(f"Remote 'origin' already exists ({remote.stdout.strip()}); pushing to it.")
        r = run(["git", "push", "-u", "origin", "HEAD"], capture=False)
    else:
        r = run(
            [
                "gh",
                "repo",
                "create",
                args.name,
                "--public",
                "--source",
                ".",
                "--remote",
                "origin",
                "--push",
                "--description",
                "My solutions: Codeforces and LeetCode",
            ],
            capture=False,
        )
    if r.returncode != 0:
        die(
            "Creating or pushing the repo failed (see the message above). "
            "If the name is taken, re-run with --name something-else."
        )
    say(f"\nDone: https://github.com/{login}/{args.name}")

    # 7. schedule ----------------------------------------------------------
    if args.no_schedule:
        say("\nSkipped the scheduled task (--no-schedule).")
    else:
        step(7, "Scheduled sync")
        schedule(args.interval)

    say(
        "\nFinished. From now on new and changed solutions are committed and pushed "
        "automatically.\nCheck what it did any time in git_sync.log, or run "
        "`py git_sync.py` to sync right now."
    )


if __name__ == "__main__":
    main()
